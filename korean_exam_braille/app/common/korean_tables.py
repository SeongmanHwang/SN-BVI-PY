# 온표(=) 뒤 본문 → 호환 자모. JAMO_COMPAT 역매핑(최장 일치) + 구 종성 별칭.
def _build_on_sign_bodies() -> list[tuple[str, str]]:
    bodies: dict[str, str] = {}
    for jamo, seq in JAMO_COMPAT_TO_ASCII.items():
        if seq.startswith(ON_SIGN) and len(seq) > 1:
            bodies[seq[1:]] = jamo
    # 구 인코딩 =14(ㄹ.)와 겹받침 ㄿ가 동일 셀열.
    # 받침 ㄿ는 음절 종성으로만 두고, 단독 온표 본문 14는 ㄹ. 로 푼다.
    # 정방향(2017)의 ㄹ. 는 온표+초성 ㄹ+마침표(="4).
    bodies.pop("14", None)
    # 2017 이전·참고 BRF: 온표+종성 허용 (ㅇ 종성 7은 드러냄표와 충돌 → 제외)
    for cell, jamo in JONGSEONG.items():
        if cell == "7":
            continue
        bodies.setdefault(cell, jamo)
    for digraph, jamo in JONGSEONG_DIGRAPHS.items():
        if digraph == "14":
            continue
        bodies.setdefault(digraph, jamo)
    for cell, jamo in CHOSEONG.items():
        bodies.setdefault(cell, jamo)
    for cell, jamo in TENSED_MAP.items():
        bodies.setdefault("," + cell, jamo)
    bodies.setdefault(CHOSEONG_IEUNG, "ㅇ")
    return sorted(bodies.items(), key=lambda kv: -len(kv[0]))


ON_SIGN_BODIES: list[tuple[str, str]] = _build_on_sign_bodies()


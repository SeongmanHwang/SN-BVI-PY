# 온표(=) 뒤 본문 → 호환 자모. JAMO_COMPAT 역매핑(최장 일치) + 초성 별칭.
# 참고 BRF는 자음에 종성 점형을 쓰지만, 초성 표기도 허용한다.
def _build_on_sign_bodies() -> list[tuple[str, str]]:
    bodies: dict[str, str] = {}
    for jamo, seq in JAMO_COMPAT_TO_ASCII.items():
        if seq.startswith(ON_SIGN) and len(seq) > 1:
            bodies[seq[1:]] = jamo
    # 초성 점형 별칭 (구 인코딩·일부 교재)
    for cell, jamo in CHOSEONG.items():
        bodies.setdefault(cell, jamo)
    for cell, jamo in TENSED_MAP.items():
        bodies.setdefault("," + cell, jamo)
    bodies.setdefault(CHOSEONG_IEUNG, "ㅇ")
    return sorted(bodies.items(), key=lambda kv: -len(kv[0]))


ON_SIGN_BODIES: list[tuple[str, str]] = _build_on_sign_bodies()
ON_SIGN_JAMO: dict[str, str] = {
    body: jamo for body, jamo in ON_SIGN_BODIES if len(body) == 1
}


def compose_hangul(cho: str, jung: str, jong: str = "") -> str | None:
    if cho not in CHO_INDEX or jung not in JUNG_INDEX or jong not in JONG_INDEX:
        return None
    return chr(
        0xAC00
        + CHO_INDEX[cho] * 21 * 28
        + JUNG_INDEX[jung] * 28
        + JONG_INDEX[jong]
    )
